def rows_in(html: str) -> int:
    return html.count("<tr>") - 1


def names(html: str) -> list[str]:
    return re.findall(r"<td>\s*(?:<a[^>]*>)?([A-Z][a-z]+ [A-Z][a-z]+)", html)


