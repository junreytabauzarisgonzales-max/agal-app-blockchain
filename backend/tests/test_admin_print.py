def test_print_templates_have_no_inline_script_or_style():
    from pathlib import Path

    for path in (Path(views.__file__).parent / "templates").glob("print_*.html"):
        text = path.read_text(encoding="utf-8")
        assert not re.search(r"<script(?![^>]*\bsrc=)", text), path
        assert "<style" not in text and not re.search(r'\sstyle="', text), path
        assert not re.search(r"\son[a-z]+=", text), path
