def test_every_resource_prints_a_list_and_a_record(admin_client, db_session_factory):
    with db_session_factory() as s:
        ana, sam = add_user(s), add_user(s, "Sam Supplier", UserRole.SUPPLIER)
        batch = add_batch(s, ana)
        event = add_event(s, batch, ana, OnChainStatus.ANCHORED)
        price = add_price(s, sam)
        msg = Message(id=uuid.uuid4(), sender_id=ana.id, recipient_id=sam.id, body="hi", occurred_at=datetime.now(timezone.utc))
        s.add(msg)
        s.commit()
        audit_row = AdminAuditLog(admin_email="admin@example.com", action="create", resource="users", summary="Created user")
        s.add(audit_row)
        s.commit()
        ids = {"users": ana.id, "prices": price.id, "batches": batch.id, "events": event.id, "messages": msg.id,
               "audit": audit_row.id}
    for key, res in RESOURCES.items():
        listing = admin_client.get(f"/admin/{key}/print")
        assert listing.status_code == 200 and f"<h1>{res.label}</h1>" in listing.text, key
        record = admin_client.get(f"/admin/{key}/{ids[key]}/print")
        assert record.status_code == 200 and "Generated by" in record.text, key
        assert 'id="sidebar"' not in record.text


