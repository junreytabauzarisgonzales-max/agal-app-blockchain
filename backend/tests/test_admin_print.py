def test_bulk_message_reports_never_include_bodies(admin_client, db_session_factory):
    with db_session_factory() as s:
        a, b = add_user(s), add_user(s, "Sam Supplier", UserRole.SUPPLIER)
        msg = Message(id=uuid.uuid4(), sender_id=a.id, recipient_id=b.id, body="TOP SECRET RENDEZVOUS", occurred_at=datetime.now(timezone.utc))
        s.add(msg)
        s.commit()
        mid = msg.id
    for url in ("/admin/messages/print", f"/admin/messages/print?id={mid}", "/admin/messages/print?scope=page",
                "/admin/messages/print?q=sam"):
        html = admin_client.get(url).text
        assert "TOP SECRET" not in html, url
        assert rows_in(html) == 1, url
    # Only the explicit single-message printout carries the text, with a privacy note.
    single = admin_client.get(f"/admin/messages/{mid}/print").text
    assert "TOP SECRET RENDEZVOUS" in single and "Private conversation" in single


